"""What an --apply run produces: the PRs it opens and the diff it pushes.

The diff reviewed in the dry run is reused on --apply, and re-derived only when
the base moved or the fix changed.
"""

import subprocess
from pathlib import Path
from typing import Any

import pytest
from gh_harness import FakeGh, branch_pushed, make_repo_with_origin, offline_clone
from test_apply_gh_calls import BRANCH, _setup
from test_main import REPO_A, REPO_B, _mock_sync, _write_fix

from repomod import main as run_fix
from repomod.status import load_status
from repomod.types import Repo

FIX_THAT_LOGS_ITS_RUNS = """\
import os
from pathlib import Path


def accept_repo(repo: dict, config: dict) -> bool:
    return True


def run(repo: Path, config: dict) -> bool:
    with open(os.environ["RUN_LOG"], "a") as log:
        log.write("run\\n")
    (repo / "README.md").write_text("changed")
    return True


def validate(repo: Path, config: dict) -> list[str]:
    with open(os.environ["RUN_LOG"], "a") as log:
        log.write("validate\\n")
    return []
"""


def _logged_fix_setup(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> tuple[Path, Path, dict[str, Path]]:
    """Like _setup, but the fix records every run()/validate() call it gets."""
    run_log = tmp_path / "runs.log"
    monkeypatch.setenv("RUN_LOG", str(run_log))
    fix_dir, origins = _setup(tmp_path)
    (fix_dir / "main.py").write_text(FIX_THAT_LOGS_ITS_RUNS)
    return fix_dir, run_log, origins


def _calls(run_log: Path, kind: str) -> int:
    return run_log.read_text().splitlines().count(kind) if run_log.exists() else 0


def _git_stdout(cwd: Path, *args: str) -> str:
    return subprocess.run(
        ["git", *args],
        cwd=cwd,
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()


def _dry_run_then_apply(fix_dir: Path, between: Any = None) -> None:
    with _mock_sync(repos=[REPO_A, REPO_B]):
        run_fix.main([str(fix_dir), "--workers", "1"])
        if between:
            between()
        run_fix.main([str(fix_dir), "--apply", "--workers", "1"])


def test_reviewers_are_requested_in_the_create_call_not_as_separate_edits(
    tmp_path: Path, fake_gh: FakeGh
) -> None:
    """The default team and the fix's reviewers all ride along on `pr create`."""
    fix_dir, _ = _setup(tmp_path)

    with _mock_sync(repos=[REPO_A]), offline_clone():
        run_fix.main([str(fix_dir), "--apply", "--workers", "1"])

    (create,) = [
        args
        for args in fake_gh.calls_for("acme/repo-alpha")
        if args[:2] == ["pr", "create"]
    ]
    reviewers = [create[i + 1] for i, a in enumerate(create) if a == "--reviewer"]
    assert reviewers == ["testuser"]
    assert fake_gh.count("pr", "edit") == 0


def test_every_pr_body_sent_to_github_ends_with_the_repomod_footer(
    tmp_path: Path, fake_gh: FakeGh
) -> None:
    fix_dir, _ = _setup(tmp_path)

    with _mock_sync(repos=[REPO_A, REPO_B]), offline_clone():
        run_fix.main([str(fix_dir), "--apply", "--workers", "1"])

    bodies = []
    for call in fake_gh.calls():
        args = call["args"]
        if args[:2] == ["pr", "create"]:
            bodies.append(args[args.index("--body") + 1])
    assert len(bodies) == 2
    for body in bodies:
        # YAML's `|` leaves a trailing newline on the fix's own text; the footer
        # is separated by exactly one blank line.
        assert body == ("Test body.\n\n---\n\nGenerated by repomod.")


def test_new_prs_are_opened_as_drafts(tmp_path: Path, fake_gh: FakeGh) -> None:
    fix_dir, _ = _setup(tmp_path)

    with _mock_sync(repos=[REPO_A, REPO_B]), offline_clone():
        run_fix.main([str(fix_dir), "--apply", "--workers", "1"])

    creates = [a for c in fake_gh.calls() if (a := c["args"])[:2] == ["pr", "create"]]
    assert len(creates) == 2
    assert all("--draft" in args for args in creates)


def test_apply_pushes_the_dry_run_diff_without_rerunning_the_fix(
    tmp_path: Path, fake_gh: FakeGh, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The diff you reviewed is the diff that is pushed; run() and validate()
    each ran once per repo (in the dry run) and not again on --apply."""
    fix_dir, run_log, origins = _logged_fix_setup(tmp_path, monkeypatch)

    _dry_run_then_apply(fix_dir)

    assert _calls(run_log, "run") == 2
    assert _calls(run_log, "validate") == 2
    assert fake_gh.count("pr", "create") == 2
    for repo in ("alpha", "beta"):
        bare = origins[f"acme/repo-{repo}"]
        assert branch_pushed(bare, BRANCH)
        pushed = subprocess.run(
            ["git", "show", f"{BRANCH}:README.md"],
            cwd=bare,
            capture_output=True,
            text=True,
            check=True,
        ).stdout
        assert pushed == "changed"
    status = load_status(fix_dir / "status.yaml")
    assert status["acme/repo-alpha"]["status"] == "pr_created"


def test_apply_reruns_the_fix_when_the_repo_moved_since_the_dry_run(
    tmp_path: Path, fake_gh: FakeGh, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The stored diff was made against an older commit, so it can't be trusted."""
    fix_dir, run_log, origins = _logged_fix_setup(tmp_path, monkeypatch)
    alpha = fix_dir / "repos" / "acme-repo-alpha"

    def upstream_moves() -> None:
        (alpha / "NEWS.md").write_text("new upstream work")
        for args in (
            ["add", "NEWS.md"],
            ["commit", "-m", "upstream"],
            ["push", "origin", "main"],
        ):
            subprocess.run(["git", *args], cwd=alpha, check=True, capture_output=True)

    _dry_run_then_apply(fix_dir, between=upstream_moves)

    assert _calls(run_log, "run") == 3  # 2 in the dry run + alpha again, not beta
    news = subprocess.run(
        ["git", "show", f"{BRANCH}:NEWS.md"],
        cwd=origins["acme/repo-alpha"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    assert news == "new upstream work"  # the PR is built on the moved base
    assert fake_gh.count("pr", "create") == 2


def test_apply_falls_back_to_the_fix_when_the_stored_patch_will_not_apply(
    tmp_path: Path, fake_gh: FakeGh, monkeypatch: pytest.MonkeyPatch
) -> None:
    fix_dir, run_log, _ = _logged_fix_setup(tmp_path, monkeypatch)
    patch_dir = next(fix_dir.glob("patches-*"), None)

    def corrupt_alpha_patch() -> None:
        (next(fix_dir.glob("patches-*")) / "acme-repo-alpha.patch").write_text(
            "diff --git a/README.md b/README.md\n--- a/README.md\n+++ b/README.md\n"
            "@@ -1 +1 @@\n-this line is not in the file\n+changed\n"
        )

    assert patch_dir is None  # created by the dry run
    _dry_run_then_apply(fix_dir, between=corrupt_alpha_patch)

    assert _calls(run_log, "run") == 3  # alpha's corrupt patch forced a re-run
    assert fake_gh.count("pr", "create") == 2
    assert (
        load_status(fix_dir / "status.yaml")["acme/repo-alpha"]["status"]
        == "pr_created"
    )


def test_apply_never_pushes_a_dry_run_diff_from_an_older_version_of_the_fix(
    tmp_path: Path, fake_gh: FakeGh, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Editing the fix after the dry run makes the stored diff stale: re-run it."""
    fix_dir, run_log, origins = _logged_fix_setup(tmp_path, monkeypatch)

    def edit_the_fix() -> None:
        source = (fix_dir / "main.py").read_text()
        (fix_dir / "main.py").write_text(source.replace('"changed"', '"changed v2"'))

    _dry_run_then_apply(fix_dir, between=edit_the_fix)

    assert _calls(run_log, "run") == 4  # both repos re-ran under the new fix
    pushed = subprocess.run(
        ["git", "show", f"{BRANCH}:README.md"],
        cwd=origins["acme/repo-alpha"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    assert pushed == "changed v2"


def test_fix_branch_equal_to_the_default_branch_is_not_pushed(
    tmp_path: Path, fake_gh: FakeGh
) -> None:
    """A fix branch named like the default branch must not be committed or pushed.

    acme/backend is on `main`, and that is the default branch the clone would
    force-push. acme/frontend's default is `master`, so the same fix branch is
    a new branch there and still gets a PR. The run does not abort.
    """
    backend = Repo(name="acme/backend", default_branch="main", topics=["rust"])
    frontend = Repo(name="acme/frontend", default_branch="master", topics=["rust"])
    fix_dir = tmp_path / "fix"
    _write_fix(fix_dir)
    config_path = fix_dir / "config.yaml"
    config_path.write_text(
        config_path.read_text().replace("branch: test-branch\n", "branch: main\n", 1)
    )

    origins: dict[str, Path] = {}
    for repo in (backend, frontend):
        clone, bare = make_repo_with_origin(tmp_path, repo.slug, repo.name)
        (fix_dir / "repos").mkdir(exist_ok=True)
        clone.rename(fix_dir / "repos" / repo.slug)
        origins[repo.name] = bare

    frontend_clone = fix_dir / "repos" / frontend.slug
    frontend_bare = origins[frontend.name]
    _git_stdout(frontend_clone, "branch", "-m", "main", "master")
    _git_stdout(frontend_clone, "push", "-u", "origin", "master")
    _git_stdout(frontend_bare, "symbolic-ref", "HEAD", "refs/heads/master")
    _git_stdout(frontend_bare, "update-ref", "-d", "refs/heads/main")

    backend_clone = fix_dir / "repos" / backend.slug
    assert _git_stdout(backend_clone, "branch", "--show-current") == "main"
    assert _git_stdout(frontend_clone, "branch", "--show-current") == "master"
    assert not branch_pushed(frontend_bare, "main")
    backend_tip = _git_stdout(origins[backend.name], "rev-parse", "main")

    with _mock_sync(repos=[backend, frontend]), offline_clone():
        assert run_fix.main([str(fix_dir), "--apply", "--workers", "1"]) == 0

    assert _git_stdout(origins[backend.name], "rev-parse", "main") == backend_tip
    status = load_status(fix_dir / "status.yaml")
    assert status["acme/backend"]["status"] == "failed"
    assert "default branch" in status["acme/backend"]["reason"]
    assert status["acme/frontend"]["status"] == "pr_created"
    assert branch_pushed(frontend_bare, "main")
    assert fake_gh.calls_for("acme/backend") == []
    assert fake_gh.count("pr", "create", repo="acme/frontend") == 1
    assert fake_gh.count("api", "--method") == 2


def test_dry_run_fix_branch_equal_to_the_default_branch_is_not_published(
    tmp_path: Path, fake_gh: FakeGh, capsys: pytest.CaptureFixture[str]
) -> None:
    """A dry run must not publish a patch it will refuse to push.

    acme/backend's fix branch is its default branch, so the run records failed
    and writes no patch. acme/frontend's default is master, so the same branch
    is still a pending patch. Nothing is pushed, and the run exits 0.
    """
    backend = Repo(name="acme/backend", default_branch="main", topics=["rust"])
    frontend = Repo(name="acme/frontend", default_branch="master", topics=["rust"])
    fix_dir = tmp_path / "fix"
    _write_fix(fix_dir)
    config_path = fix_dir / "config.yaml"
    config_path.write_text(
        config_path.read_text().replace("branch: test-branch\n", "branch: main\n", 1)
    )

    origins: dict[str, Path] = {}
    for repo in (backend, frontend):
        clone, bare = make_repo_with_origin(tmp_path, repo.slug, repo.name)
        (fix_dir / "repos").mkdir(exist_ok=True)
        clone.rename(fix_dir / "repos" / repo.slug)
        origins[repo.name] = bare

    frontend_clone = fix_dir / "repos" / frontend.slug
    frontend_bare = origins[frontend.name]
    _git_stdout(frontend_clone, "branch", "-m", "main", "master")
    _git_stdout(frontend_clone, "push", "-u", "origin", "master")
    _git_stdout(frontend_bare, "symbolic-ref", "HEAD", "refs/heads/master")
    _git_stdout(frontend_bare, "update-ref", "-d", "refs/heads/main")

    backend_tip = _git_stdout(origins[backend.name], "rev-parse", "main")
    frontend_tip = _git_stdout(origins[frontend.name], "rev-parse", "master")
    assert not branch_pushed(frontend_bare, "main")

    with _mock_sync(repos=[backend, frontend]), offline_clone():
        assert run_fix.main([str(fix_dir), "--workers", "1"]) == 0

    assert _git_stdout(origins[backend.name], "rev-parse", "main") == backend_tip
    assert _git_stdout(origins[frontend.name], "rev-parse", "master") == frontend_tip
    assert not branch_pushed(frontend_bare, "main")
    assert fake_gh.count("pr", "create") == 0
    assert fake_gh.calls_for("acme/backend") == []

    status = load_status(fix_dir / "status.yaml")
    assert status["acme/backend"]["status"] == "failed"
    assert (
        status["acme/backend"]["reason"]
        == "fix branch main is the repo's default branch"
    )
    assert status["acme/frontend"]["status"] == "pending"
    assert list(fix_dir.glob("patches-*/acme-backend.patch")) == []
    frontend_patch = fix_dir.glob("patches-*/acme-frontend.patch")
    assert "changed" in next(frontend_patch).read_text()
    out = capsys.readouterr().out
    assert "1 failed" in out
    assert "interrupted" not in out
