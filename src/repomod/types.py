"""Shared types for the repomod pipeline."""

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, NamedTuple, Protocol

import yaml

from repomod.ui import ProgressDisplay

Status = dict[str, dict[str, str]]


class FixModule(Protocol):
    """Interface implemented by loaded fixes."""

    def accept_repo(self, repo: dict[str, Any], config: dict[str, Any]) -> bool: ...

    def run(self, repo: Path, config: dict[str, Any]) -> bool: ...


@dataclass(frozen=True)
class Repo:
    """A GitHub repository from repos.yaml."""

    name: str
    default_branch: str
    topics: list[str]
    # Date of the newest non-bot default-branch commit seen at sync time. Activity
    # only ages out, so a recent one lets later syncs skip re-checking this repo.
    last_human_commit: str | None = None

    @property
    def slug(self) -> str:
        """'acme/backend' → 'acme-backend'"""
        return self.name.replace("/", "-")

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> Repo:
        return cls(
            name=d["name"],
            default_branch=d["default_branch"],
            topics=d["topics"],
            last_human_commit=d.get("last_human_commit"),
        )

    def to_dict(self) -> dict[str, Any]:
        """What fixes see in accept_repo(): the stable repo facts only."""
        return {
            "name": self.name,
            "default_branch": self.default_branch,
            "topics": self.topics,
        }

    def to_record(self) -> dict[str, Any]:
        """What repos.yaml stores: the repo facts plus the sync memo."""
        record = self.to_dict()
        if self.last_human_commit is not None:
            record["last_human_commit"] = self.last_human_commit
        return record


@dataclass(frozen=True)
class PRSpec:
    """Everything needed to create/update a PR."""

    repo_name: str
    branch: str
    title: str
    body: str
    reviewers: list[str]


# Appended to every PR body so reviewers can tell where a PR came from. Mandatory:
# applied in FixConfig.pr_spec, not part of any fix's config.yaml.
PR_FOOTER = "---\n\nGenerated by repomod."


# The GitHub owners repomod works on, written as search qualifiers. joshuarli is a
# user, laputa-systems an organization; GitHub ORs `user:` and `org:` in one query.
OWNER_QUALIFIERS = ("user:joshuarli", "org:laputa-systems")


def _require_string(value: object, key: str) -> str:
    if not isinstance(value, str):
        raise ValueError(f"{key} must be a string, got {type(value).__name__}")
    return value


def _require_string_list(value: object, key: str) -> None:
    if not isinstance(value, list):
        raise ValueError(
            f"{key} must be a list of strings, got {type(value).__name__}"
        )
    for item in value:
        if not isinstance(item, str):
            raise ValueError(
                f"{key} must be a list of strings, got {type(item).__name__}"
            )


@dataclass(frozen=True)
class FixConfig:
    """Validated fix configuration from config.yaml."""

    branch: str
    pr_title: str
    pr_body: str
    reviewers: list[str] = field(default_factory=list)
    sparse_paths: list[str] | None = None
    skip: list[str] = field(default_factory=list)
    extra: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        _require_string_list(self.reviewers, "reviewers")
        if self.sparse_paths is not None:
            _require_string_list(self.sparse_paths, "sparse_paths")
        _require_string_list(self.skip, "skip")

    @classmethod
    def from_yaml(cls, path: Path) -> FixConfig:
        with open(path) as f:
            raw = yaml.safe_load(f)
        if not isinstance(raw, dict):
            raise ValueError(
                f"Expected a YAML mapping in {path}, got {type(raw).__name__}"
            )
        missing = {"branch", "pr_title", "pr_body"} - raw.keys()
        if missing:
            raise ValueError(
                f"Config missing required keys: {', '.join(sorted(missing))}"
            )
        known = {
            "branch",
            "pr_title",
            "pr_body",
            "reviewers",
            "sparse_paths",
            "skip",
        }
        reviewers = raw.get("reviewers")
        skip = raw.get("skip")
        return cls(
            branch=_require_string(raw["branch"], "branch"),
            pr_title=_require_string(raw["pr_title"], "pr_title"),
            pr_body=_require_string(raw["pr_body"], "pr_body"),
            reviewers=[] if reviewers is None else reviewers,
            sparse_paths=raw.get("sparse_paths"),
            skip=[] if skip is None else skip,
            extra={k: v for k, v in raw.items() if k not in known},
        )

    def as_dict(self) -> dict[str, Any]:
        d: dict[str, Any] = {
            "branch": self.branch,
            "pr_title": self.pr_title,
            "pr_body": self.pr_body,
            "reviewers": self.reviewers,
            "sparse_paths": self.sparse_paths,
            "skip": self.skip,
        }
        d.update(self.extra)
        return d

    def pr_spec(self, repo_name: str) -> PRSpec:
        body = self.pr_body.rstrip()
        return PRSpec(
            repo_name=repo_name,
            branch=self.branch,
            title=self.pr_title,
            body=f"{body}\n\n{PR_FOOTER}",
            reviewers=list(self.reviewers),
        )


class SyncResult(NamedTuple):
    """Outcome of a repo sync: repos to run fixes on, and names dropped as inactive."""

    repos: list[Repo]
    excluded: list[str]


class PRInfo(NamedTuple):
    """A pull request for a fix branch. state is GitHub's: OPEN, MERGED, CLOSED."""

    url: str
    state: str
    # GitHub's immutable GraphQL id; empty when not yet known (a freshly created PR).
    node_id: str = ""


class RolloutPR(NamedTuple):
    """A PR on a fix's branch, as found on GitHub. state: OPEN, MERGED, CLOSED."""

    repo: str
    url: str
    state: str
    draft: bool
    node_id: str = ""


class LintFinding(NamedTuple):
    """An actionlint error. Line numbers are omitted so findings can be compared
    before and after a fix moves lines around."""

    path: str
    message: str


class WorkItem(NamedTuple):
    repo: Repo
    stale_reason: str | None = None


@dataclass
class RunContext:
    """Shared context for all worker threads in a single run."""

    fix: FixModule
    config: FixConfig
    config_dict: dict[str, Any]
    fix_hash: str
    accepted_hashes: frozenset[str]
    repos_dir: Path
    logs_dir: Path
    patches_dir: Path
    status_file: Path
    apply: bool
    all_status: Status
    pd: ProgressDisplay
    existing_prs: dict[str, RolloutPR]
